"use strict";

/**
 * open-core-exclusions.cjs — the one list of what must never reach the public
 * community tree.
 *
 * WHY ONE FILE. This is the same lesson scripts/leak-patterns.cjs records, and
 * it was learned here the same way. The builder (scripts/build-community.cjs)
 * kept `EXCLUDE_DIRS`; the validator (scripts/validate-open-core.cjs) kept
 * `INTERNAL_DIRS`. Both listed agent and IDE state directories, and neither
 * listed `.clinerules/` — nine files of internal agent steering — so the
 * builder copied it into the payload and the validator reported PASS on it.
 * Two lists maintained by hand do not stay in step; the one that guards the
 * push is the one that quietly falls behind.
 *
 * THREE KINDS OF ENTRY, and the distinction matters:
 *
 *   INTERNAL_DIR_NAMES     Directory basenames that are internal WHEREVER they
 *                          appear. The builder skips them; the validator fails
 *                          on them at any depth, not just at the tree root.
 *
 *   INTERNAL_REL_PATHS     Specific repo-relative paths that are internal, while
 *                          a directory of the same basename elsewhere is not.
 *
 *   BUILD_ARTIFACT_DIRS    Not secret, just not source. The builder must skip
 *                          them; the validator must NOT fail on them, because
 *                          the payload's own .gitignore keeps them out of the
 *                          commit and they are regenerated by whoever builds.
 */

