// ── What gets scanned ────────────────────────────────────────────────────────
// An extension allowlist is an exclusion list that nobody calls one, and it
// fails the same way: silently. Both scanners used to look only at .md .txt
// .json .yml .yaml .js .cjs .mjs .ts, so `start-interactive.ps1` — which
// hardcoded one machine's checkout path on line 3 and had already been
// published — was never read by either gate. Sniff the bytes instead: anything
// that is not obviously binary gets scanned, whatever it is called.
const fs = require("fs");

const SCAN_MAX_BYTES = 8 * 1024 * 1024; // a lockfile fits; a bundled binary does not
const SNIFF_BYTES = 8192;

/**
 * Read a file as text, or return null if it is empty, oversized or binary.
 * "Binary" means a NUL byte in the leading window — the same heuristic grep
 * uses for -I, and it is what keeps a 7 MB vendored executable out of the scan.
 */
function readScannableText(absPath) {
  let buf;
  try {
    buf = fs.readFileSync(absPath);
  } catch {
    return null;
  }
  if (buf.length === 0 || buf.length > SCAN_MAX_BYTES) return null;
  if (buf.subarray(0, Math.min(buf.length, SNIFF_BYTES)).includes(0)) return null;
  return buf.toString("utf8");
}

/** True if a directory with this basename is internal wherever it sits. */
function isInternalDirName(name) {
  return INTERNAL_DIR_NAMES.includes(name);
}

/** True if this repo-relative path is one of the specific internal paths. */
function isInternalRelPath(rel) {
  const r = String(rel).replace(/\\/g, "/").replace(/\/+$/, "");
  return INTERNAL_REL_PATHS.includes(r);
}

/** True if a file with this basename must never be copied or published. */
function isInternalFileName(name) {
  return INTERNAL_FILE_REGEXES.some((re) => re.test(name));
}

/**
 * Throws unless the lists still cover the cases that have actually bitten.
 * Both scripts call this at load, for the same reason the leak patterns
 * self-test: a list that has quietly stopped covering something reports PASS.
 */
function selfTest() {
  const failures = [];
  const mustExcludeDir = [".clinerules", ".claude", ".autoclaw", ".kiro", ".fork", "plans", "archive"];
  for (const d of mustExcludeDir) {
    if (!isInternalDirName(d)) failures.push(`directory "${d}" is not excluded`);
  }
  const mustKeepDir = ["src", "docs", "scripts", "tests", "public", "config", "open-sse"];
  for (const d of mustKeepDir) {
    if (isInternalDirName(d)) failures.push(`directory "${d}" is excluded but is product`);
  }
  const mustExcludeFile = ["CLAUDE.md", "AGENTS.md", ".cursorrules", ".env", ".env.local", "app.log"];
  for (const f of mustExcludeFile) {
    if (!isInternalFileName(f)) failures.push(`file "${f}" is not excluded`);
  }
  const mustKeepFile = [
    "README.md",
    "CONTRIBUTING.md",
    "LICENSE",
    "SECURITY.md",
    "ARCHITECTURE.md",
    ".env.example",
    "package.json",
  ];
  for (const f of mustKeepFile) {
    if (isInternalFileName(f)) failures.push(`file "${f}" is excluded but is product`);
  }
  if (!isInternalRelPath("docs/_internal")) failures.push("docs/_internal is not excluded");
  if (isInternalRelPath("docs")) failures.push("all of docs/ is excluded");
  // A build artifact must not be reported as an internal leak; the payload's
  // own .gitignore keeps it out of the commit.
  for (const d of ["node_modules", ".next"]) {
    if (isInternalDirName(d)) failures.push(`build artifact "${d}" is reported as an internal leak`);
  }
  // The scan-scope heuristic is part of the gate, so pin it here too.
  const os = require("os");
  const tmp = fs.mkdtempSync(require("path").join(os.tmpdir(), "occ-selftest-"));
  const j = (n) => require("path").join(tmp, n);
  try {
    fs.writeFileSync(j("a.ps1"), "Set-Location C:/x\n");
    if (readScannableText(j("a.ps1")) === null) failures.push("a PowerShell script is not scanned");
    fs.writeFileSync(j("b.sh"), "#!/bin/sh\ncd /x\n");
    if (readScannableText(j("b.sh")) === null) failures.push("a shell script is not scanned");
    fs.writeFileSync(j("c.bin"), Buffer.from([0x7f, 0x45, 0x4c, 0x46, 0x00, 0x01]));
    if (readScannableText(j("c.bin")) !== null) failures.push("a binary file is scanned as text");
    fs.writeFileSync(j("d.txt"), "");
    if (readScannableText(j("d.txt")) !== null) failures.push("an empty file is scanned");
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }

  if (failures.length) {
    throw new Error("open-core-exclusions self-test FAILED:\n  - " + failures.join("\n  - "));
  }
  return INTERNAL_DIR_NAMES.length + INTERNAL_FILE_REGEXES.length;
}

module.exports = {
  INTERNAL_DIR_NAMES,
  readScannableText,
  SCAN_MAX_BYTES,
  INTERNAL_REL_PATHS,
  BUILD_ARTIFACT_DIRS,
  INTERNAL_FILE_REGEXES,
  AGENT_FILE_REGEXES,
  isInternalDirName,
  isInternalRelPath,
  isInternalFileName,
  selfTest,
};

if (require.main === module) {
  const n = selfTest();
  console.log(`open-core-exclusions: self-test PASS — ${n} rules`);
}
